package com.swent.roamigo.model.trip

import kotlinx.coroutines.flow.Flow

/**
 * Defines the activity data operations required by the presentation layer.
 *
 * Reading a trip's activities once stays on [TripRepository.getActivitiesForTrip]; this interface
 * adds creation and live observation. Only [ActivityType.ACCEPTED] activities can be created for
 * now. Any member of the trip may create one; roles are not enforced yet.
 */
interface ActivityRepository {

  /**
   * Creates an activity from [draft] in the trip [tripId], authored by the current user.
   *
   * The author, creation time, and [ActivityType.ACCEPTED] type are never supplied by the caller.
   *
   * [activityId] is generated by the caller once per draft. Calling again with the same
   * [activityId] by the same author returns the existing activity and creates nothing new, which
   * makes retries safe. The returned activity is the stored one, so a retry ignores any change made
   * to [draft] since the first call.
   *
   * @param tripId the trip the activity belongs to.
   * @param activityId the identifier of the activity to create, generated by the caller.
   * @param draft the details chosen by the user.
   * @return the created activity, or the existing one when [activityId] was already created by the
   *   current user.
   * @throws ActivityCreationException.Validation if [draft] is invalid.
   * @throws ActivityCreationException for any other failure, using the matching subtype.
   */
  suspend fun createActivity(tripId: String, activityId: String, draft: ActivityDraft): Activity

  /**
   * Observes the activities of a trip, emitting the full list again after every change.
   *
   * Collection fails if the stored data cannot be read or the current user may not see the trip.
   * Activities are emitted in no particular order.
   *
   * @param tripId the trip whose activities are observed.
   */
  fun observeActivities(tripId: String): Flow<List<Activity>>
}
