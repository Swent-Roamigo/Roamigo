package com.swent.roamigo.model.trip.activity

import com.swent.roamigo.model.trip.Activity
import com.swent.roamigo.model.trip.ActivityType
import com.swent.roamigo.model.trip.TripRepository
import kotlinx.coroutines.flow.Flow

/**
 * Defines the activity data operations required by the presentation layer.
 *
 * Reading a trip's activities once stays on [TripRepository.getActivitiesForTrip]; this interface
 * adds accepted activity creation and live observation. Use [SuggestionVoteRepository] to create
 * suggestions.
 */
interface ActivityRepository {

  /**
   * Creates an activity from [draft] in the trip [tripId], authored by the current user as an
   * accepted activity.
   *
   * The author, creation time, and [ActivityType.ACCEPTED] type are never supplied by the caller.
   * An accepted activity is part of the itinerary, so [draft] must have a start time.
   *
   * [activityId] is generated by the caller once per draft. Calling again with the same
   * [activityId] by the same author returns the existing accepted activity without writing. The
   * retry draft is ignored, even if it is invalid.
   *
   * @param tripId the trip the activity belongs to.
   * @param activityId the identifier of the activity to create, generated by the caller.
   * @param draft the details chosen by the user.
   * @return the created activity, or the existing one when [activityId] was already created by the
   *   current user as an accepted activity.
   * @throws IllegalArgumentException if [tripId] or [activityId] is not a valid document ID: blank,
   *   containing a slash, or equal to "." or "..". This is a caller bug, not a creation failure.
   * @throws ActivityCreationException.Validation if creating a new activity with an invalid
   *   [draft], including when it has no start time.
   * @throws ActivityCreationException.PermissionDenied if another author owns [activityId] or the
   *   current user lacks permission.
   * @throws ActivityCreationException.TypeConflict if the current user owns [activityId] as a
   *   suggestion.
   * @throws ActivityCreationException for any other failure, using the matching subtype.
   */
  suspend fun createActivity(tripId: String, activityId: String, draft: ActivityDraft): Activity

  /**
   * Observes the activities of a trip, emitting the full list again after every change.
   *
   * Collection fails if the stored data cannot be read or the current user may not see the trip.
   * Both types are emitted in no particular order, including suggestions without a proposed start.
   *
   * @param tripId the trip whose activities are observed.
   */
  fun observeActivities(tripId: String): Flow<List<Activity>>
}

internal fun Activity.requireCreationMatch(authorId: String, type: ActivityType): Activity {
  if (createdByUserId != authorId) throw ActivityCreationException.PermissionDenied()
  if (activityType != type) throw ActivityCreationException.TypeConflict(type, activityType)
  return this
}
