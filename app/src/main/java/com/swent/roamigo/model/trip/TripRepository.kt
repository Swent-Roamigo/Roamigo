package com.swent.roamigo.model.trip

/**
 * Defines the trip-related data operations required by the presentation layer.
 *
 * ViewModels depend on this interface rather than on a concrete data source, allowing Firebase and
 * in-memory implementations to be exchanged without changing presentation code.
 */
interface TripRepository {

  /** Returns all trips belonging to the current user. */
  suspend fun getTrips(): List<Trip>

  /** Returns the activities belonging to the requested trip. */
  suspend fun getActivitiesForTrip(tripId: String): List<Activity>

  /** Returns the members belonging to the requested trip. */
  suspend fun getMembersForTrip(tripId: String): List<TripMember>

  /**
   * Creates a trip from [draft], owned by the currently authenticated user.
   *
   * The owner is never supplied by the caller. The trip and its [TripMemberRole.OWNER] [TripMember]
   * are created together, so one never exists without the other.
   *
   * [tripId] is generated by the caller once per draft. Calling again with the same [tripId] by the
   * same owner returns the existing trip and creates nothing new, which makes retries safe.
   *
   * Once created, the trip is returned by subsequent [getTrips] calls, and its owner by
   * [getMembersForTrip] with [tripId].
   *
   * @param tripId the identifier of the trip to create, generated by the caller.
   * @param draft the details chosen by the user.
   * @return the created trip, or the existing one when [tripId] was already created by this owner.
   * @throws TripCreationException.Validation if [draft] is invalid.
   * @throws TripCreationException for any other failure, using the matching subtype.
   */
  suspend fun createTrip(tripId: String, draft: TripDraft): Trip
}
